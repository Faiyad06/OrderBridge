"""Independent reference verifier for the OrderBridge reference case.

Deliberately does NOT import the application engine. It recomputes the six
scenarios with plain integer minor units straight from the build brief (section 8),
asserts the published table, and (with --write) regenerates
fixtures/expected_results.json and fixtures/expected_daily_balances.csv.

Usage:  python scripts/verify_reference.py [--write]
"""
from __future__ import annotations

import csv
import json
import sys
from datetime import date, timedelta
from decimal import ROUND_HALF_UP, Decimal
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DAY0 = date(2026, 10, 1)
HORIZON = 46
OPENING = 100_000_00
BUFFER = 20_000_00

EXISTING = [(1, +60_000_00), (2, -50_000_00), (7, -40_000_00), (14, +80_000_00), (21, -30_000_00), (30, +60_000_00)]
ORDER = {"rcpt": (45, +220_000_00), "mat": (3, -140_000_00), "ful": (10, -20_000_00)}
DEPOSIT = [(0, +66_000_00), (45, +154_000_00)]
DEFERRAL = [(3, -70_000_00), (46, -70_000_00)]
LOAN_PRINCIPAL = 110_000_00
INTEREST = int((Decimal(LOAN_PRINCIPAL) * Decimal("0.12") * 43 / 365).quantize(Decimal("1"), rounding=ROUND_HALF_UP))
FEE = 500_00


def events(name: str) -> list[tuple[int, int]]:
    ev = list(EXISTING)
    if name == "no_order":
        return ev
    rcpt, mat = [ORDER["rcpt"]], [ORDER["mat"]]
    if name in ("buyer_deposit", "combined_terms"):
        rcpt = DEPOSIT
    if name in ("supplier_deferral", "combined_terms"):
        mat = DEFERRAL
    ev += rcpt + mat + [ORDER["ful"]]
    if name == "illustrative_loan":
        ev += [(3, LOAN_PRINCIPAL), (46, -LOAN_PRINCIPAL), (46, -INTEREST), (46, -FEE)]
    return ev


def project(name: str) -> list[int]:
    ev = events(name)
    bal, out = OPENING, []
    for d in range(HORIZON + 1):
        bal += sum(a for day, a in ev if day == d)
        out.append(bal)
    return out


def metrics(name: str, daily: list[int]) -> dict:
    low = min(daily)
    low_day = daily.index(low)
    neg = next((d for d, b in enumerate(daily) if b < 0), None)
    breach = next((d for d, b in enumerate(daily) if b < BUFFER), None)
    contribution = 0 if name == "no_order" else 60_000_00
    fin_cost = INTEREST + FEE if name == "illustrative_loan" else 0
    return {
        "lowest_balance_minor": low,
        "lowest_balance_day": low_day,
        "lowest_balance_date": (DAY0 + timedelta(low_day)).isoformat(),
        "first_negative_day": neg,
        "first_negative_date": None if neg is None else (DAY0 + timedelta(neg)).isoformat(),
        "first_buffer_breach_day": breach,
        "required_support_minor": max(0, BUFFER - low),
        "ending_balance_minor": daily[-1],
        "contribution_before_financing_minor": contribution,
        "financing_cost_minor": fin_cost,
        "contribution_after_financing_minor": contribution - fin_cost,
        "borrowed_principal_minor": LOAN_PRINCIPAL if name == "illustrative_loan" else 0,
    }


PUBLISHED = {  # brief section 8 table, CNY minor units
    "no_order": (70_000_00, None, 0, 180_000_00),
    "current_terms": (-90_000_00, 3, 110_000_00, 240_000_00),
    "buyer_deposit": (-24_000_00, 7, 44_000_00, 240_000_00),
    "supplier_deferral": (-20_000_00, 10, 40_000_00, 240_000_00),
    "combined_terms": (46_000_00, None, 0, 240_000_00),
    "illustrative_loan": (20_000_00, None, 0, 237_944_93),
}


def main() -> int:
    results, rows, failures = {}, [], []
    for name, (low, neg, sup, end) in PUBLISHED.items():
        daily = project(name)
        m = metrics(name, daily)
        results[name] = m
        got = (m["lowest_balance_minor"], m["first_negative_day"], m["required_support_minor"], m["ending_balance_minor"])
        status = "OK " if got == (low, neg, sup, end) else "FAIL"
        if status == "FAIL":
            failures.append(name)
        print(f"{status} {name:18s} low={got[0]/100:>11.2f} first_neg={got[1]!s:>4} support={got[2]/100:>10.2f} end={got[3]/100:>11.2f} min_day={m['lowest_balance_day']}")
        for d, b in enumerate(daily):
            rows.append({"scenario_id": name, "day": d, "date": (DAY0 + timedelta(d)).isoformat(), "closing_balance_minor": b})
    checks = [
        ("interest 1555.07", INTEREST == 155507),
        ("current_terms min day 10", results["current_terms"]["lowest_balance_day"] == 10),
        ("combined_terms min day 10", results["combined_terms"]["lowest_balance_day"] == 10),
        ("loan contribution after cost 57944.93", results["illustrative_loan"]["contribution_after_financing_minor"] == 57_944_93),
    ]
    for label, ok in checks:
        print(("OK  " if ok else "FAIL") + " " + label)
        if not ok:
            failures.append(label)
    if "--write" in sys.argv:
        (ROOT / "fixtures/expected_results.json").write_text(json.dumps(
            {"_note": "Synthetic reference results; generated by scripts/verify_reference.py independently of the app engine.",
             "loan_interest_minor": INTEREST, "loan_fee_minor": FEE, "scenarios": results}, indent=2) + "\n")
        with open(ROOT / "fixtures/expected_daily_balances.csv", "w", newline="") as f:
            w = csv.DictWriter(f, fieldnames=["scenario_id", "day", "date", "closing_balance_minor"])
            w.writeheader()
            w.writerows(rows)
        print("wrote fixtures/expected_results.json and fixtures/expected_daily_balances.csv")
    return 1 if failures else 0


if __name__ == "__main__":
    raise SystemExit(main())
